import { test, expect } from '@playwright/test';
test('register, create and edit board/task, move, reload and delete', async ({ page, isMobile }) => {
  const browserErrors: string[] = [];
  page.on('pageerror', error => browserErrors.push(error.message));
  const email = `browser-${Date.now()}-${Math.random()}@example.com`;
  await page.goto('/');
  await page.getByRole('button', { name: 'Create an account' }).click();
  await page.getByLabel('Your name').fill('Browser Reviewer');
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('StrongPass123!');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByRole('button', { name: 'Create your first board' }).click();
  await page.getByLabel('Board name').fill('Review project');
  await page.getByLabel('Description').fill('A project that persists');
  await page.getByRole('button', { name: 'Create board', exact: true }).last().click();
  await expect(page.getByRole('heading', { name: 'Review project' })).toBeVisible();
  await page.getByRole('button', { name: 'Add task', exact: true }).first().click();
  await page.getByLabel('Task title').fill('Write launch checklist');
  await page.getByLabel('Description').fill('Check the working application');
  await page.getByRole('button', { name: 'Create task', exact: true }).click();
  const card = page.getByTestId('task-card').filter({ hasText: 'Write launch checklist' });
  await expect(page.getByTestId('column-todo').getByTestId('task-card')).toHaveCount(1);
  if (isMobile) await card.getByLabel('Move Write launch checklist').selectOption('in_progress');
  else await card.dragTo(page.getByTestId('column-in_progress'));
  await expect(page.getByTestId('column-in_progress').getByTestId('task-card')).toHaveCount(1);
  await page.reload();
  await expect(page.getByTestId('column-in_progress').getByTestId('task-card')).toHaveCount(1);
  await page.getByRole('button', { name: 'Edit Write launch checklist' }).click();
  await page.getByLabel('Task title').fill('Launch checklist complete');
  await page.getByRole('dialog').locator('select[name="status"]').selectOption('done');
  await page.getByRole('button', { name: 'Save task', exact: true }).click();
  await expect(page.getByTestId('column-done')).toContainText('Launch checklist complete');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: `docs/screenshots/board-${isMobile ? 'mobile' : 'desktop'}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Edit board', exact: true }).click();
  await page.getByLabel('Board name').fill('Ready for review');
  await page.getByRole('button', { name: 'Save board', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Ready for review' })).toBeVisible();
  await page.locator('button[aria-label="Sign out"]:visible').click();
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('StrongPass123!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByTestId('column-done')).toContainText('Launch checklist complete');
  await page.getByRole('button', { name: 'Edit Launch checklist complete' }).click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete task', exact: true }).click();
  await expect(page.getByTestId('task-card')).toHaveCount(0);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete board', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your next project belongs here.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  expect(browserErrors).toEqual([]);
});
