import { test, expect, type Locator } from '@playwright/test';
test.use({ timezoneId: 'America/Los_Angeles' });
test('calendar date ranges, overlap filters, month boundaries and unscheduled tasks', async ({ page, isMobile }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.clock.setFixedTime(new Date('2026-10-16T12:00:00Z'));
  await page.goto('/');
  await page.getByRole('button', { name: 'Create an account' }).click();
  await page.getByLabel('Your name').fill('Calendar Reviewer');
  await page.getByLabel('Email address').fill(`calendar-${Date.now()}-${Math.random()}@example.com`);
  await page.getByLabel('Password', { exact: true }).fill('StrongPass123!');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByRole('button', { name: 'Create your first board' }).click();
  await page.getByLabel('Board name').fill('Calendar project');
  await page.getByRole('button', { name: 'Create board', exact: true }).last().click();
  await expect(page.getByRole('heading', { name: 'Calendar project' })).toBeVisible();
  async function createTask(title: string, start = '', end = '') {
    await page.getByRole('button', { name: 'Add task', exact: true }).first().click();
    await page.getByLabel('Task title').fill(title);
    if (start) await page.getByLabel('Start date').fill(start);
    if (end) await page.getByLabel('End date').fill(end);
    await page.getByRole('button', { name: 'Create task', exact: true }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
  }
  await createTask('Release preparation', '2026-10-10', '2026-10-12');
  await createTask('Overlapping design', '2026-10-12', '2026-10-14');
  await createTask('Month boundary', '2026-10-31', '2026-11-01');
  await createTask('Unscheduled idea');
  await page.getByRole('button', { name: 'Calendar', exact: true }).click();
  await expect(page.getByTestId('calendar-month')).toHaveText('October 2026');
  const bars = (title = 'Release preparation') => page.locator('[data-testid^="calendar-event-"]').filter({ hasText: title });
  const range = (start: string, end: string, title = 'Release preparation') => page.locator(`[data-testid^="calendar-event-"][data-start="${start}"][data-end="${end}"]`).filter({ hasText: title });
  const color = (bar: Locator) => bar.evaluate(el => getComputedStyle(el).backgroundColor);
  await expect(bars()).toHaveCount(2);
  await expect(range('2026-10-10', '2026-10-10')).toHaveCount(1);
  await expect(range('2026-10-11', '2026-10-12')).toHaveCount(1);
  const releaseColor = await color(bars().first());
  expect(await color(bars().last())).toBe(releaseColor);
  await expect(bars('Overlapping design')).toHaveCount(1);
  const overlap = range('2026-10-12', '2026-10-14', 'Overlapping design');
  await expect(overlap).toHaveCount(1);
  const span = await overlap.evaluate(el => ({ start: getComputedStyle(el).gridColumnStart, end: getComputedStyle(el).gridColumnEnd }));
  expect(Number(span.end) - Number(span.start)).toBe(3);
  const overlapColor = await color(overlap);
  expect(overlapColor).not.toBe(releaseColor);
  expect(await overlap.getAttribute('data-lane')).not.toBe(await range('2026-10-11', '2026-10-12').getAttribute('data-lane'));
  const releaseBox = await range('2026-10-11', '2026-10-12').boundingBox();
  const overlapBox = await overlap.boundingBox();
  expect(releaseBox).not.toBeNull();
  expect(overlapBox).not.toBeNull();
  expect(Math.abs(releaseBox!.y - overlapBox!.y)).toBeGreaterThanOrEqual(Math.min(releaseBox!.height, overlapBox!.height));
  await expect(range('2026-10-31', '2026-10-31', 'Month boundary')).toHaveCount(1);
  await expect(range('2026-11-01', '2026-11-01', 'Month boundary')).toHaveCount(1);
  await expect(page.getByRole('region', { name: 'Unscheduled tasks' })).toContainText('Unscheduled idea');
  await page.getByLabel('Filter from date').fill('2026-10-11');
  await page.getByLabel('Filter to date').fill('2026-10-11');
  await expect(bars()).toHaveCount(1);
  await expect(range('2026-10-11', '2026-10-11')).toHaveCount(1);
  expect(await color(range('2026-10-11', '2026-10-11'))).toBe(releaseColor);
  await expect(bars('Month boundary')).toHaveCount(0);
  await page.getByLabel('Filter from date').fill('2026-10-12');
  await page.getByLabel('Filter to date').fill('2026-10-12');
  await expect(range('2026-10-12', '2026-10-12')).toHaveCount(1);
  await page.getByLabel('Filter from date').fill('2026-10-20');
  await page.getByLabel('Filter to date').fill('2026-10-21');
  await expect(page.getByText('No scheduled tasks overlap this date range.')).toBeVisible();
  await page.getByLabel('Filter to date').fill('2026-10-19');
  await expect(page.getByRole('alert')).toContainText('filter end date');
  await page.getByRole('button', { name: 'Clear filters' }).click();
  await range('2026-10-10', '2026-10-10').click();
  await page.getByLabel('Start date').fill('2026-10-11');
  await page.getByLabel('End date').fill('2026-10-13');
  await page.getByRole('button', { name: 'Save task', exact: true }).click();
  await expect(bars()).toHaveCount(1);
  await expect(range('2026-10-11', '2026-10-13')).toHaveCount(1);
  await page.reload();
  await page.getByRole('button', { name: 'Calendar', exact: true }).click();
  await expect(range('2026-10-11', '2026-10-13')).toHaveCount(1);
  expect(await color(bars().first())).toBe(releaseColor);
  expect(await color(bars('Overlapping design').first())).toBe(overlapColor);
  await page.getByRole('button', { name: 'Next month', exact: true }).click();
  await expect(page.getByTestId('calendar-month')).toHaveText('November 2026');
  await expect(range('2026-11-01', '2026-11-01', 'Month boundary')).toHaveCount(1);
  await page.getByRole('button', { name: 'Today', exact: true }).click();
  await expect(page.getByTestId('calendar-month')).toHaveText('October 2026');
  await page.getByRole('button', { name: 'Create task on 2026-10-16', exact: true }).click();
  await expect(page.getByLabel('Start date')).toHaveValue('2026-10-16');
  await expect(page.getByLabel('End date')).toHaveValue('2026-10-16');
  await page.getByLabel('Task title').fill('One-day milestone');
  await page.getByRole('button', { name: 'Create task', exact: true }).click();
  await expect(range('2026-10-16', '2026-10-16', 'One-day milestone')).toHaveCount(1);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.evaluate(() => { window.scrollTo(0, 0); const grid = document.querySelector('.calendar-scroll'); if (grid) grid.scrollLeft = 0; });
  await page.screenshot({ path: `docs/screenshots/calendar-${isMobile ? 'mobile' : 'desktop'}.png`, fullPage: true });
  await range('2026-10-11', '2026-10-13').click();
  await page.getByLabel('Start date').fill('');
  await page.getByLabel('End date').fill('');
  await page.getByRole('button', { name: 'Save task', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Unscheduled tasks' })).toContainText('Release preparation');
  await page.reload();
  await page.getByRole('button', { name: 'Calendar', exact: true }).click();
  await expect(page.getByRole('region', { name: 'Unscheduled tasks' })).toContainText('Release preparation');
  expect(errors).toEqual([]);
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Delete board', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your next project belongs here.' })).toBeVisible();
});
