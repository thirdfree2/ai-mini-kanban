import { test, expect } from '@playwright/test';
const api = process.env.API_BASE_URL || 'http://localhost:8080/api';
test('authentication, persistence, task lifecycle and ownership protection', async ({ playwright }) => {
  const owner = await playwright.request.newContext();
  const stranger = await playwright.request.newContext();
  const suffix = `${Date.now()}-${Math.random()}`;
  const credentials = { name: 'QA Owner', email: `owner-${suffix}@example.com`, password: 'StrongPass123!' };
  const register = await owner.post(`${api}/auth/register`, { data: credentials });
  expect(register.status()).toBe(200);
  expect((await owner.get(`${api}/auth/me`)).status()).toBe(200);
  const created = await owner.post(`${api}/boards`, { data: { name: 'QA project', description: 'Persistence test' } });
  expect(created.status()).toBe(201);
  const { board } = await created.json();
  const createdTask = await owner.post(`${api}/boards/${board.id}/tasks`, { data: { title: 'QA task', description: 'Initial', status: 'todo' } });
  expect(createdTask.status()).toBe(201);
  const { task } = await createdTask.json();
  await stranger.post(`${api}/auth/register`, { data: { name: 'Other user', email: `other-${suffix}@example.com`, password: credentials.password } });
  expect((await stranger.get(`${api}/boards/${board.id}/tasks`)).status()).toBe(404);
  expect((await stranger.patch(`${api}/tasks/${task.id}`, { data: { title: 'Stolen', status: 'done' } })).status()).toBe(404);
  expect((await stranger.delete(`${api}/tasks/${task.id}`)).status()).toBe(404);
  expect((await stranger.delete(`${api}/boards/${board.id}`)).status()).toBe(404);
  expect((await stranger.get(`${api}/boards`)).ok()).toBeTruthy();
  expect((await (await stranger.get(`${api}/boards`)).json()).boards).toEqual([]);
  const update = await owner.patch(`${api}/tasks/${task.id}`, { data: { title: 'Updated QA task', description: 'Saved', status: 'done', position: 0 } });
  expect(update.ok()).toBeTruthy();
  const list = await owner.get(`${api}/boards/${board.id}/tasks`);
  expect((await list.json()).tasks).toEqual(expect.arrayContaining([expect.objectContaining({ id: task.id, title: 'Updated QA task', status: 'done' })]));
  expect((await owner.patch(`${api}/boards/${board.id}`, { data: { name: 'Renamed QA board', description: 'Updated' } })).ok()).toBeTruthy();
  expect((await owner.post(`${api}/auth/logout`)).ok()).toBeTruthy();
  expect((await owner.get(`${api}/boards`)).status()).toBe(401);
  expect((await owner.post(`${api}/auth/login`, { data: { email: credentials.email, password: credentials.password } })).ok()).toBeTruthy();
  expect((await (await owner.get(`${api}/boards`)).json()).boards).toEqual(expect.arrayContaining([expect.objectContaining({ id: board.id, name: 'Renamed QA board' })]));
  expect((await owner.delete(`${api}/tasks/${task.id}`)).status()).toBe(204);
  expect((await owner.delete(`${api}/boards/${board.id}`)).status()).toBe(204);
  await owner.dispose();
  await stranger.dispose();
});
